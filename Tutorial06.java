// About Math in java.

public class Tutorial06 {
    public static void main(String[] args) {
        
        //finding the max of two numbers
        System.out.println("Maximum of 5 and 6 using max : " + Math.max(5,6));

        //finding the min of two numbers
        System.out.println("Minimum of 5 and 6 using the min : " + Math.min(5,6));

        //finding the square root of number
        System.out.println("Square root of 5 using the sqrt : " + Math.sqrt(5));

        //finding the cube root of number
        System.out.println("Cube root of 5 using the sqrt : " + Math.cbrt(5));

        //finding the power of nums
        System.out.println("Power 4 of 6 : " + Math.pow(6, 4));

        //finding the ceil and floor and round
        System.out.println("Using the ceil (2.3) : " + Math.ceil(2.3));
        System.out.println("Using the floor (2.7) : " + Math.floor(2.7));
        System.out.println("Using the round (2.6) : " + Math.round(2.7));

        //using the abs 
        System.out.println("Absolute value of -3.4 : " + Math.abs(-3.4));

        // And many more methods are available in java ......
    }
}
